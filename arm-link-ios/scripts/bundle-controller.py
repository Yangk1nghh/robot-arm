"""Generate the bundled module graph; no eval or downloaded runtime patch."""
from pathlib import Path
import base64,json
root=Path(__file__).resolve().parents[1]
origin='https://arduino-arm-3d-viewer.freshauk74.chatgpt.site'
base=origin+'/viewer/'
modules={}
for name in ['arm-core.js','optimistic.js','joystick.js','sync.js','app.js']:
    source=(root/'controller'/name).read_text()
    for dep,url in modules.items(): source=source.replace("'./"+dep+"'",json.dumps(url))
    for dep in ['three.js','SVGRenderer.js']: source=source.replace("'./"+dep+"'",json.dumps(base+dep))
    modules[name]='data:text/javascript;base64,'+base64.b64encode(source.encode()).decode()
bootstrap='''// ARM Link smooth controller 1.2.2. Generated by scripts/bundle-controller.py.
(()=>{
 if(location.origin!==ORIGIN||!location.pathname.startsWith('/viewer/')||!document.querySelector('#leftStick')||window.__armSmoothController)return;
 window.__armSmoothController='1.2.2';
 const script=document.createElement('script');script.type='module';script.src=ENTRY;
 script.onerror=()=>{const e=document.querySelector('#syncError');if(e){e.hidden=false;e.textContent='控制模組載入失敗，請重新整理。';}};
 document.body.appendChild(script);
})();
'''.replace('ORIGIN',json.dumps(origin)).replace('ENTRY',json.dumps(modules['app.js']))
(root/'App'/'ControllerFix.js').write_text(bootstrap)
print('Bundled smooth controller modules:',len(modules))
